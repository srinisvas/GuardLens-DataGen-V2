#!/usr/bin/env python3
"""Paired counterfactual evidence analysis for the NAACL validity repair.

This is a narrow replacement for the invalid v11 causal-analysis passes. It
keeps the already-generated user trajectories and recomputes intervention
evidence under a controlled replay protocol.

Validity guarantees
-------------------
1. Stored assistant responses are never mixed into a replay. Every assistant
   response is regenerated by the replay target model.
2. Baseline and counterfactual trajectories use the same target model, decoding
   parameters, and deterministic per-turn seed schedule.
3. Response generation and outcome judgment use different model families. The
   intended run is Llama target replay plus Mistral judge.
4. Full conversation history is retained. There is no position-dependent
   12-message sliding window.
5. Span interventions are tested independently. They are not gated on a
   successful pivot-turn intervention.
6. ``counterfactual_delta = null`` means not assessed. Zero is reserved for an
   actually measured zero effect.
7. If the baseline is already unsafe before an intervention turn, that
   intervention is marked not assessable rather than treated as negative
   evidence.

The legacy fields ``causal_type`` and ``supervision_tier`` are populated only
for compatibility with the existing GuardLens model code. The NAACL paper
should describe the new fields as counterfactual evidence, not causal ground
truth.
"""

