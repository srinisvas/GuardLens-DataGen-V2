# Dataset generation with progress tracking
# =========================================================

def generate_interactive_dataset(
    generator_backend: InferenceBackend,
    target_backend: InferenceBackend,
    n_pairs: int = 1000,
    random_seed: int = 42,
    checkpoint_path: Optional[str] = None,
    checkpoint_interval: int = 10,
) -> List[Dict]:
    """
    Generate n_pairs interactive adversarial conversations.
    Supports checkpoint/resume.
    """
    random.seed(random_seed)

    attacker = InteractiveAttackGenerator(
        generator_backend=generator_backend,
        target_backend=target_backend,
    )

    dataset = []
    start_pair = 0

    # Resume from checkpoint
    if checkpoint_path and os.path.exists(checkpoint_path):
        with open(checkpoint_path, "r") as f:
            for line in f:
                if line.strip():
                    dataset.append(json.loads(line))
        start_pair = len(dataset) // 2  # Each pair produces 2 records
        print(f"Resuming from checkpoint: {len(dataset)} records, starting at pair {start_pair}")

    start_time = time.time()
    ckpt_file = open(checkpoint_path, "a") if checkpoint_path else None

    try:
        for i in range(start_pair, n_pairs):
            mal, ben = attacker.generate_pair()
            dataset.extend([mal, ben])

            # Checkpoint
            if ckpt_file:
                ckpt_file.write(json.dumps(mal, ensure_ascii=False) + "\n")
                ckpt_file.write(json.dumps(ben, ensure_ascii=False) + "\n")
                ckpt_file.flush()

            if (i + 1) % checkpoint_interval == 0:
                elapsed = (time.time() - start_time) / 60
                pairs_done = i + 1 - start_pair
                rate = pairs_done / max(elapsed, 0.01)
                remaining = (n_pairs - i - 1) / max(rate, 0.01)

                jailbreaks = sum(
                    1 for r in dataset
                    if r.get("label") == 1
                    and r.get("llama_validation", {}).get("jailbreak_detected")
                )
                mal_count = sum(1 for r in dataset if r.get("label") == 1)

                print(f"  {i + 1}/{n_pairs} pairs ({len(dataset)} records) "
                      f"[{elapsed:.0f}m elapsed, ~{remaining:.0f}m remaining] "
                      f"jailbreak rate: {jailbreaks}/{mal_count}")

    finally:
        if ckpt_file:
            ckpt_file.close()

    return dataset


