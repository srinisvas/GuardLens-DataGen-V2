def main():
    parser = argparse.ArgumentParser(
        description="Interactive adversarial dataset generation (v11)"
    )
    parser.add_argument("--n-pairs", type=int, default=1000)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", type=str,
                        default="./output/interactive_raw.jsonl")

    # Generator (Qwen-14B)
    parser.add_argument("--generator-backend", type=str, default="vllm")
    parser.add_argument("--generator-model", type=str,
                        default="Qwen/Qwen2.5-14B-Instruct")
    parser.add_argument("--generator-url", type=str,
                        default="http://localhost:8000")

    # Target (Llama-8B)
    parser.add_argument("--target-backend", type=str, default="vllm")
    parser.add_argument("--target-model", type=str,
                        default="meta-llama/Meta-Llama-3-8B-Instruct")
    parser.add_argument("--target-url", type=str,
                        default="http://localhost:9000")

    # Checkpointing
    parser.add_argument("--checkpoint", type=str, default=None,
                        help="Checkpoint file for resume support")
    parser.add_argument("--checkpoint-interval", type=int, default=10)

    args = parser.parse_args()

    generator_backend = create_backend(
        backend_type=args.generator_backend,
        model=args.generator_model,
        base_url=args.generator_url,
    )
    target_backend = create_backend(
        backend_type=args.target_backend,
        model=args.target_model,
        base_url=args.target_url,
    )

    checkpoint = args.checkpoint
    if checkpoint is None:
        checkpoint = args.output + ".checkpoint"

    print(f"Generator: {args.generator_model} at {args.generator_url}")
    print(f"Target:    {args.target_model} at {args.target_url}")
    print(f"Pairs:     {args.n_pairs}")
    print(f"Output:    {args.output}")
    print()

    dataset = generate_interactive_dataset(
        generator_backend=generator_backend,
        target_backend=target_backend,
        n_pairs=args.n_pairs,
        random_seed=args.seed,
        checkpoint_path=checkpoint,
        checkpoint_interval=args.checkpoint_interval,
    )

    gen.write_jsonl(dataset, args.output)
    print(f"\nWrote {len(dataset)} records to {args.output}")

    # Statistics
    mal = [r for r in dataset if r.get("label") == 1]
    jb = sum(1 for r in mal if r.get("llama_validation", {}).get("jailbreak_detected"))
    strategies = {}
    for r in mal:
        s = r.get("metadata", r.get("attack_metadata", {})).get("strategy", "unknown")
        strategies[s] = strategies.get(s, 0) + 1

    print(f"\nStatistics:")
    print(f"  Total: {len(dataset)} ({len(mal)} malicious, {len(dataset) - len(mal)} benign)")
    print(f"  Jailbreaks (Llama target): {jb}/{len(mal)} ({jb / max(len(mal), 1) * 100:.1f}%)")
    print(f"  Strategies: {json.dumps(strategies, indent=4)}")


if __name__ == "__main__":
    main()
