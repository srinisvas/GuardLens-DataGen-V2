"""
interactive_generator.py

Adaptive adversarial conversation generator. A strong generator model
(Qwen-14B) crafts user turns against a live target model (Llama-8B),
adapting based on the target's actual responses.

Key design:
  - Generator sees target's real refusals and adapts strategy
  - Target model is different family from validation model
  - Structured judge scores each target response in-loop
  - Failed attacks kept as hard negatives (valuable training data)
  - Benign twins generated by replaying setup + benign continuation

Output is compatible with v11 pipeline schema (ConversationSample).

Usage:
    python interactive_generator.py \\
        --generator-url http://localhost:8000 \\
        --generator-model Qwen/Qwen2.5-14B-Instruct \\
        --target-url http://localhost:9000 \\
        --target-model meta-llama/Meta-Llama-3-8B-Instruct \\
        --n-pairs 1000 \\
        --output output/interactive_raw.jsonl
"""

